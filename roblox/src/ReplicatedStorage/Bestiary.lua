-- Rend la liste des indices d'espèces d'une rareté (ordre croissant d'indice).
function Bestiary.speciesOfTier(tier)
	local out = {}
	for i, d in ipairs(Bestiary.PETS) do
		if d.tier == tier then
			out[#out + 1] = i
		end
	end
	return out
end

-- Description normalisée du repli procédural d'une espèce (jamais nil pour un indice valide) : sert au Builder et aux tests « chaque modèle a un repli ».
function Bestiary.fallback(idx)
	local d = Bestiary.PETS[idx]
	if not d then
		return nil
	end
	return { color = d.color, ears = d.ears, extra = d.extra, extra2 = d.extra2, accent = d.accent, glow = d.glow == true, scale = d.scale or 1 }
end

